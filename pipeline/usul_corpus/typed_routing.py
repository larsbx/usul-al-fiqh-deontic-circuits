"""T3/T4 of the type system: routing by type, measured on the IslamQA tranche.

Each answer of the tranche was typed blind (without its labels) into one or more partial situations:
the fields of `Usul.Typing.Qaida` the text settles, each with a verbatim quote of at most 160
characters (``corpus/typing/islamqa_tranche1_situations.json``; LLM-assisted, status candidate).
They are written out as ``sit/3`` facts (``examples/v41_islamqa_situations.pl``) and routed by the
Prolog typing rules (``examples/v41_typing.pl``, exported from Lean): an encoder applies when a
situation settles every field it reads, and encoders are ranked by the share they settle
(``coverage/4``, relations included). Ties count against the true encoder. The report sets this
against the lexical baseline (``corpus/routing/ood.json``) on the same cases.
"""

from __future__ import annotations

import json
import subprocess
from collections import defaultdict
from pathlib import Path

from .fatawa_prolog import atom

SITUATIONS = "corpus/typing/islamqa_tranche1_situations.json"
PROLOG = "examples/v41_islamqa_situations.pl"
REPORT = "corpus/typing/islamqa_tranche1_report.json"
TRANCHE = "corpus/fatawa/takhrij/islamqa_tranche1.json"
TYPING = "examples/v41_typing.pl"
KS = (1, 5, 10)


def sid(answer: str, i: int) -> str:
    return f"s_{answer.replace('.', '_')}_{i}"


def prolog_file(data: dict) -> str:
    lines = [f"% GENERATED by `python -m usul_corpus typed-routing` from {SITUATIONS}. Do not edit.",
             ":- encoding(utf8).", ":- multifile([sit/3, situation_of/2]).", ":- discontiguous([sit/3, situation_of/2]).", ""]
    for a in data["answers"]:
        for i, s in enumerate(a["situations"], 1):
            lines.append(f"situation_of({sid(a['answer'], i)}, {atom(a['answer'])}).")
            lines += [f"sit({sid(a['answer'], i)}, {f}, {atom(v)})." for f, v in sorted(s["facts"].items())]
    return "\n".join(lines) + "\n"


def coverage(root: Path) -> dict[str, dict[str, tuple[int, int]]]:
    """answer ↦ encoder ↦ (fields settled, fields read), best over the answer's situations (needs swipl)."""
    goal = ("forall((coverage(E,S,K,N), K > 0, situation_of(S,A)), format('~w\\t~w\\t~w\\t~w~n',[A,E,K,N]))")
    out = subprocess.run(["swipl", "-q", "-g", goal, "-t", "halt", str(root / TYPING), str(root / PROLOG)],
                         capture_output=True, text=True, check=True).stdout
    best: dict[str, dict[str, tuple[int, int]]] = defaultdict(dict)
    for a, e, k, n in (l.split("\t") for l in out.splitlines()):
        k, n = int(k), int(n)
        if k / n > (lambda p: p[0] / p[1])(best[a].get(e, (0, 1))):
            best[a][e] = (k, n)
    return best


def report(root: Path, cov: dict[str, dict[str, tuple[int, int]]]) -> dict:
    data = json.loads((root / SITUATIONS).read_text(encoding="utf-8"))
    cases = json.loads((root / TRANCHE).read_text(encoding="utf-8"))["cases"]
    typed = {a["answer"] for a in data["answers"]}
    hits, applied, rows = defaultdict(int), 0, []
    for c in cases:
        a = c["far"].rsplit(".", 1)[0]
        scores = {e: k / n for e, (k, n) in cov.get(a, {}).items()}
        s = scores.get(c["encoder"], 0.0)
        rank = sum(v >= s for v in scores.values()) if s > 0 else None
        applied += s == 1.0
        for k in KS:
            hits[k] += rank is not None and rank <= k
        rows.append({"case": c["far"], "encoder": c["encoder"], "settled": round(s, 4), "rank": rank})
    n = len(cases)
    routed = [sum(v == 1.0 for v in cov.get(a, {}).values()) for a in sorted(typed)]
    lexical = json.loads((root / "corpus/routing/ood.json").read_text(encoding="utf-8"))
    return {"schema_version": 1, "status": "candidate",
            "method": "blind typing into Usul.Typing situations; Prolog routing by coverage of each encoder's fields",
            "answers": len(typed), "situations": sum(len(a["situations"]) for a in data["answers"]),
            "fields_stated": sum(len(s["facts"]) for a in data["answers"] for s in a["situations"]),
            "cases": n, "applies": round(applied / n, 4),
            "recall": {str(k): round(hits[k] / n, 4) for k in KS},
            "lexical_recall": lexical["recall"], "lexical_prior": lexical["prior"],
            "encoders_applying_per_answer": round(sum(routed) / len(routed), 2) if routed else 0,
            "cases_detail": rows}


def render(root: Path) -> tuple[str, str]:
    """The situations as Prolog, and the report computed from the committed Prolog file."""
    data = json.loads((root / SITUATIONS).read_text(encoding="utf-8"))
    return prolog_file(data), json.dumps(report(root, coverage(root)), ensure_ascii=False, indent=2) + "\n"
