from usul_corpus.hudud import extract_hudud
from usul_corpus.openiti import Section


def test_extract_hudud_takes_istilahi_definition():
    secs = (
        Section(1, "[الأحكام]", "الأحكام: جمع حُكم وهو لغةً: القضاء.واصطلاحاً: ما اقْتضاه خطاب الشرع المتعلق بأفعال المكلفين من طلب، أو تخيير، أو وضع.فالمراد بقولنا", (1, 10), (1, 10)),
        Section(1, "[أقسام الأحكام]", "تنقسم الأحكام إلى قسمين", (1, 10), (1, 10)),
        Section(1, "[الواجب]", "الواجب لغة: الساقط واللازم. واصطلاحاً: ما أمر به الشارع على وجه الإلزام كالصلوات الخمس.", (1, 11), (1, 11)),
    )
    hs = extract_hudud(secs)
    assert [h.term for h in hs] == ["الأحكام", "الواجب"]
    assert hs[0].lughatan == "القضاء"
    assert hs[0].istilahan == "ما اقْتضاه خطاب الشرع المتعلق بأفعال المكلفين من طلب، أو تخيير، أو وضع"
    assert hs[1].istilahan.startswith("ما أمر به الشارع على وجه الإلزام")
    assert hs[1].page == (1, 11)


def test_extract_hudud_one_per_definition_in_a_multi_definition_section():
    text = "\n".join([
        "فالتكليفية خمسة: الواجب والمندوب.",
        "١ - فالواجب لغة: الساقط واللازم.",
        "واصطلاحاً: ما أمر به الشارع على وجه الإلزام؛ كالصلوات الخمس.",
        "فخرج بقولنا: «ما أمر به الشارع»؛ المحرم.",
        "٢ - والمندوب لغة: المدعوُّ.",
        "واصطلاحاً: ما أمر به الشارع لا على وجه الإلزام؛ كالرواتب.",
    ])
    hs = extract_hudud((Section(1, "[أقسام الأحكام الشرعية]", text, (1, 10), (1, 10)),))
    assert [(h.term, h.lughatan) for h in hs] == [("الواجب", "الساقط واللازم"), ("المندوب", "المدعوُّ")]
    assert hs[1].istilahan == "ما أمر به الشارع لا على وجه الإلزام؛ كالرواتب"


def test_extract_hudud_term_from_generic_heading():
    a = Section(1, "[تعريفه]", "النسخ لغة: الإزالة والنقل.\nواصطلاحاً: رفع حكم دليل شرعي.", (1, 51), (1, 51))
    b = Section(1, "[تعريف المطلق]", "واصطلاحاً: ما دل على الحقيقة بلا قيد.", (1, 44), (1, 44))
    c = Section(1, "[تعريفه]", "واصطلاحاً: بذل الجهد.", (1, 85), (1, 85))
    assert [h.term for h in extract_hudud((a, b, c))] == ["النسخ", "المطلق", "تعريفه"]
