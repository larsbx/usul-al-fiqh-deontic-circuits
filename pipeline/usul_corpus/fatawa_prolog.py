"""A Prolog oracle over the IslamQA takhrīj cases.

The tranche (``corpus/fatawa/takhrij``) gives each case its encoder and the
encoder's facts; the classical takhrīj cases (``corpus/takhrij``) of the same
encoders join as a held-out set the rules were not written against; ``corpus/fatawa/prolog/*_facts.json`` adds the other facts its
text states and the text's own ruling. This module writes both out as Prolog
(``examples/v40_fatwa_cases.pl``) for the rules in ``examples/v40_fatwa_rules.pl``,
with two kinds of fixture vector per case:

    bank(C)    the Prolog bank reproduces the Python/Lean kernel on C's encoder facts
    agrees(C)  the oracle's ruling is the text's; expect_false for a case the
               facts file records as an ``oracle_gap`` (with its reason), on
               the premise that the oracle answers it at all
    within_positions(C)
               for a disputed case (``positions``, each with its reasoning):
               the oracle takes one of the reported positions. No position is
               the target by attribution; which is right is a matter of its
               proof (tarjīḥ), so these cases are not scored for agreement

The gap ledger is written by hand: a disagreement is either fixed in the rules
or recorded there, never absorbed silently.
"""

from __future__ import annotations

import json
import re
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

from . import fatawa_takhrij, judgement, takhrij

RULES = "examples/v40_fatwa_rules.pl"
CASES = "examples/v40_fatwa_cases.pl"
FIXTURES = "examples/v40_fatwa_oracle_fixtures.pl"
SKIP = {"segmentation_error"}  # not a case of its encoder


def load_facts(corpus: Path) -> dict[str, dict]:
    """Extended facts per case; a case given in two places is refused, not silently shadowed."""
    entries = [(f.name, c) for f in sorted((corpus / "fatawa" / "prolog").glob("*_facts.json"))
               for c in json.loads(f.read_text(encoding="utf-8"))["cases"]]
    seen = Counter(c["far"] for _, c in entries)
    if dup := sorted(i for i, n in seen.items() if n > 1):
        raise ValueError("facts given more than once: " + ", ".join(
            f"{i} ({', '.join(name for name, c in entries if c['far'] == i)})" for i in dup))
    return {c["far"]: c for _, c in entries}


def load_cases(corpus: Path, facts: dict[str, dict]) -> list[dict]:
    """The IslamQA tranche, and the classical cases the facts files bring in."""
    return fatawa_takhrij.load(corpus) + [c for c in takhrij.load(corpus) if c["far"] in facts]


def source(far: str) -> str:
    return "islamqa" if far.startswith("islamqa.") else "classical"


def merge(cases: list[dict], facts: dict[str, dict]) -> list[dict]:
    """One record per oracle case: encoder facts as annotated, extended facts (text over tranche; null drops)."""
    out = []
    for c in cases:
        if c["class"] in SKIP:
            continue
        x = facts[c["far"]]
        enc = {k: v for k, v in (c.get("facts") or {}).items() if v is not None}
        ext = {k: v for k, v in ({**enc, **x["facts"]}).items() if v is not None}
        domain = takhrij.ENCODERS[c["encoder"]]["facts"]
        complete = set(enc) == set(domain) and all(enc[k] in dom for k, dom in domain.items())
        out.append(dict(far=c["far"], encoder=c["encoder"], encoder_facts=enc, facts=ext, ruling=x.get("ruling"),
                        post_hoc=x.get("post_hoc", []),
                        positions=[p["ruling"] for p in x.get("positions", [])],
                        kernel=takhrij.ENCODERS[c["encoder"]]["py"](enc) if complete else None,
                        gap=x.get("oracle_gap")))
    return out


def check(cases: list[dict], facts: dict[str, dict]) -> list[str]:
    """Every tranche case has facts and a ruling, and every facts entry a tranche case."""
    fars = {c["far"] for c in cases}
    errs = [f"{f}: no extended facts" for f in sorted(fars - set(facts))]
    errs += [f"{f}: not a tranche case" for f in sorted(set(facts) - fars)]
    errs += [f"{f}: neither one ruling nor two positions" for f, x in facts.items()
             if (x.get("ruling") is None) == (len(x.get("positions", [])) < 2)]
    errs += [f"{f}: oracle_gap without a reason" for f, x in facts.items()
             if "oracle_gap" in x and not str(x["oracle_gap"]).strip()]
    return errs


def atom(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    s = str(v)
    return s if re.fullmatch(r"[a-z][A-Za-z0-9_]*", s) else "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def prolog_file(records: list[dict]) -> str:
    lines = [":- encoding(utf8).",
             "% GENERATED by `python -m usul_corpus fatawa-prolog` from corpus/fatawa/takhrij/*.json",
             "% and corpus/fatawa/prolog/*_facts.json. Do not edit.", ""]
    lines += [f":- multifile({p})." for p in ("encoder/2", "fact/3", "fixture_expectation/3")]
    lines += [f":- discontiguous({p})." for p in ("encoder/2", "encoder_fact/3", "fact/3", "text_ruling/2", "position/2",
                                                   "fixture_expectation/3", "fixture_premise/2")]
    for r in records:
        c = atom(r["far"])
        lines += ["", f"encoder({c}, {r['encoder']})."]
        lines += [f"encoder_fact({c}, {k}, {atom(v)})." for k, v in sorted(r["encoder_facts"].items())]
        lines += [f"fact({c}, {k}, {atom(v)})." for k, v in sorted(r["facts"].items())]
        if r["kernel"] is not None:
            lines.append(f"fixture_expectation(bank({c}), query(bank({c}, {atom(r['kernel'])})), expect_true).")
        if r["positions"]:
            lines += [f"position({c}, {atom(p)})." for p in r["positions"]]
            lines.append(f"fixture_expectation(within_positions({c}), query(within_positions({c})), expect_true).")
            continue
        lines.append(f"text_ruling({c}, {atom(r['ruling'])}).")
        if r["gap"]:
            lines.append(f"% oracle gap: {r['gap']}")
            lines.append(f"fixture_expectation(agrees({c}), query(agrees({c})), expect_false).")
            lines.append(f"fixture_premise(agrees({c}), query(text_ruling({c}, _))).")
            lines.append(f"fixture_premise(agrees({c}), query(oracle({c}, _, _))).")
        else:
            lines.append(f"fixture_expectation(agrees({c}), query(agrees({c})), expect_true).")
    return "\n".join(lines) + "\n"


def run(root: Path) -> dict[str, dict]:
    """The oracle's answer per case: {far: {ruling, rule}} (needs swipl)."""
    goal = ("forall(encoder(C,_), ( oracle(C,R,Rule) -> format('~w\\t~w\\t~w~n',[C,R,Rule])"
            " ; format('~w\\t-\\t-~n',[C]) ))")
    out = subprocess.run(["swipl", "-q", "-g", goal, "-t", "halt", str(root / FIXTURES)],
                         capture_output=True, text=True, check=True).stdout
    return {f: {"ruling": r, "rule": rule} for f, r, rule in (l.split("\t") for l in out.splitlines())}


def _same(a, b) -> bool:
    return {atom(a), atom(b)} <= {"hold", "handToAuthority"} or atom(a) == atom(b)


def sorts(corpus: Path) -> dict[str, str]:
    """Encoder → what its output answers (corpus/types/encoders.json), for the per-sort split."""
    types = judgement.load(corpus)
    return {e: judgement.sort_of(types, e) for e in types}


_REVISION = re.compile(r"^rule_revision\((\w+), (added|changed)\)\.$", re.M)


def revised_rules(root: Path) -> set[str]:
    """Rules the rules file declares added or changed after the first run (`rule_revision/2`)."""
    return {r for r, _ in _REVISION.findall((root / RULES).read_text(encoding="utf-8"))}


def report(records: list[dict], answers: dict[str, dict], revised: frozenset[str] = frozenset(),
           sorts: dict[str, str] | None = None) -> dict:
    """Agreement with decided rulings, for the oracle and the bank alone; disputed cases apart.

    The IslamQA figures are a fit (the rules were written and revised against those texts); the classical
    ones are held out. ``first_pass`` counts the agreements that need no revised rule and no post-hoc fact.
    ``per_sort`` splits by what the encoder's output answers (corpus/types/encoders.json), since agreement
    on a sabab question and on an effect are not the same measure."""
    sorts = sorts or {}
    per: dict[str, dict[str, Counter]] = defaultdict(lambda: defaultdict(Counter))
    by_sort: dict[str, dict[str, Counter]] = defaultdict(lambda: defaultdict(Counter))
    rules: dict[str, Counter] = defaultdict(Counter)
    for r in records:
        a, s = answers[r["far"]], source(r["far"])
        for k in (per[s][r["encoder"]], per[s]["total"], by_sort[s][sorts.get(r["encoder"], "untyped")]):
            if r["positions"]:
                k["disputed"] += 1
                k["oracle_within_positions"] += any(_same(a["ruling"], p) for p in r["positions"])
                continue
            agree = _same(a["ruling"], r["ruling"])
            k["decided"] += 1
            k["oracle"] += agree
            k["first_pass"] += agree and a["rule"] not in revised and not r["post_hoc"]
            k["bank_answers"] += r["kernel"] is not None
            k["bank"] += r["kernel"] is not None and _same(r["kernel"], r["ruling"])
        rules[s][a["rule"]] += 1
    fit = {"islamqa": "in_sample", "classical": "held_out"}
    return {s: {"fit": fit[s], "total": dict(p.pop("total")),
                "per_encoder": {e: dict(k) for e, k in sorted(p.items())},
                "per_sort": {t: dict(k) for t, k in sorted(by_sort[s].items())},
                "rules_fired": dict(rules[s].most_common())} for s, p in sorted(per.items())} | {
            "revised_rules": sorted(revised),
            "post_hoc_facts": {r["far"]: r["post_hoc"] for r in records if r["post_hoc"]},
            "gaps": {r["far"]: r["gap"] for r in records if r["gap"]},
            "tarjih_worklist": sorted(r["far"] for r in records if r["positions"])}
