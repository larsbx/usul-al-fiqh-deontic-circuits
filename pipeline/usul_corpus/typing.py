"""The Python mirror of the type system in ``formal/lean/Usul/Typing.lean``.

Lean is the authority: the situation type, each encoder's local signature, ``proj``/``embed`` and
their laws are declared and proved there. Python registers only which encoders are typed, under
which Lean constant, and the order of their local facts (the components of ``Local``). The
generated ``UsulTest/TypedMirror.lean`` guards, for every combination of fact values, that the typed
encoder judges the embedded situation exactly as ``takhrij.ENCODERS`` does; a wrong order or a
drifted mirror fails the kernel. Encoders not yet listed are T2's backlog.
"""

from __future__ import annotations

from itertools import product

from . import takhrij

LEAN = "formal/lean/UsulTest/TypedMirror.lean"

# encoder ↦ (its Typed constant in Usul.Typing, its facts in the order of Local's components)
TYPED = {
    "itlaf": ("Usul.Typing.itlaf", ("purpose", "mental")),
    "trust_loss": ("Usul.Typing.trustLoss", ("hand", "transgressed", "negligent")),
    "trust_voidance": ("Usul.Typing.trustVoidance", ("pure_trust", "transgressed")),
    "excused_error": ("Usul.Typing.excusedError", ("others_right", "negligent")),
    "asl_zahir": ("Usul.Typing.aslZahir", ("asl_grade", "zahir_grade", "amara")),
}


def coverage() -> dict:
    return {"typed": len(TYPED), "encoders": len(takhrij.ENCODERS)}


def lean() -> str:
    lines = ["-- GENERATED by `python -m usul_corpus typing` from typing.TYPED and takhrij.ENCODERS. Do not edit.",
             "-- Each typed encoder (Usul.Typing) judges the embedded situation as the encoder registry does.",
             "import Usul.Typing", ""]
    for name, (const, order) in sorted(TYPED.items()):
        domains = [takhrij.ENCODERS[name]["facts"][f] for f in order]
        lines.append(f"-- {name}")
        for values in product(*domains):
            local = ", ".join(takhrij.literal(name, f, v) for f, v in zip(order, values))
            facts = dict(zip(order, values))
            lines.append(f"#guard {const}.judge ({const}.embed ({local})) == some ({takhrij.lean_expr(name, facts)})")
    return "\n".join(lines) + "\n"
