"""Render the dossier of adopted principles and the glossary of terms as Markdown.

The JSON under `corpus/dossier/` is the single source; the pages under `docs/` are generated
from it (`python -m usul_corpus docs`), and a test keeps the two in sync. A reference is either
a committed record id (whose own excerpt is quoted) or a `src:` locator into a registered
witness (which carries its excerpt inline).
"""

from __future__ import annotations

HEADER = "<!-- GENERATED by `python -m usul_corpus docs` from {src}. Do not edit. -->\n\n"


def _quote(ref: dict, records: dict[str, dict]) -> str:
    rec = records.get(ref["ref"], {})
    excerpt = ref.get("excerpt_ar") or rec.get("excerpt_ar") or rec.get("case_ar", "")
    line = f"- `{ref['ref']}`: {ref['note']}"
    return line + (f"\n  > {excerpt}" if excerpt else "")


def _lean(names: list[str]) -> str:
    return ", ".join(f"`{n}`" for n in names)


def _terms(keys: list[str], glossary: dict[str, dict]) -> str:
    return ", ".join(f"[{glossary[k]['tr']}](../glossary.md#{k})" if k in glossary else k for k in keys)


def render_dossier(d: dict, records: dict[str, dict], glossary: dict[str, dict]) -> str:
    def entry(e: dict) -> str:
        cons = f"`{e['conservative']}`" if e["conservative"] else "none (a new principle, not a refinement of an earlier reading)"
        return "\n".join([
            f"<a id=\"{e['id']}\"></a>\n\n## {e['title']}",
            "",
            f"**Terms:** {_terms(e['terms'], glossary)}  ",
            f"**Closes:** {', '.join(f'`{t}`' for t in e['closes'])}  ",
            f"**Register:** {', '.join(e['iq']) or '—'}",
            "",
            "**Statement**",
            "",
            _quote(e["statement"], records),
            "",
            "**Conditions**",
            "",
            *(f"{i}. {c}" for i, c in enumerate(e["conditions"], 1)),
            "",
            "**Texts**",
            "",
            *(_quote(r, records) for r in e["refs"]),
            "",
            f"**Rationale.** {e['rationale']}",
            "",
            f"**Lean:** {_lean(e['lean'])}  ",
            f"**Conservative over the earlier reading:** {cons}",
            "",
        ])
    return (HEADER.format(src="corpus/dossier/refinements.json")
            + f"# Dossier: {d['subject']}\n\nStatus: `{d['status']}`. {d['provenance']}\n\n"
            + "\n".join(entry(e) for e in d["entries"]))


def render_glossary(g: dict, records: dict[str, dict], footer: str = "") -> str:
    def term(t: dict) -> str:
        return "\n".join([
            f"<a id=\"{t['key']}\"></a>\n\n## {t['tr']} ({t['ar']})",
            "",
            f"*{t['gloss']}.* {t['definition']}",
            "",
            *(["**Conditions**", "", *(f"- {c}" for c in t["conditions"]), ""] if t.get("conditions") else []),
            *([f"**Related:** {', '.join(f'[{r}](#{r})' for r in t['related'])}", ""] if t.get("related") else []),
            *([f"**Lean:** {_lean(t['lean'])}", ""] if t.get("lean") else []),
            "**Texts**",
            "",
            *(_quote(r, records) for r in t["refs"]),
            "",
        ])
    terms = sorted(g["terms"], key=lambda t: t["key"])
    return (HEADER.format(src="corpus/dossier/glossary.json")
            + f"# Glossary\n\nStatus: `{g['status']}`. {g['provenance']}\n\n"
            + "\n".join(term(t) for t in terms)
            + (f"\n---\n\n{footer}\n" if footer else ""))
