# The roadmap's M5 exit (§3): the carriers agree on 10^4 generated AFs. Each carrier regenerates the AFs
# from this seeded MMIX LCG and must reproduce the digest of their grounded extensions.
STRESS = {"seed": 1421, "count": 10_000, "n_max": 7, "num": 1, "den": 4}
LCG_A, LCG_C, MOD64, P61 = 6364136223846793005, 1442695040888963407, 1 << 64, (1 << 61) - 1

NAMED = [
    ("unattacked", "an uncontested naṣṣ", 1, []),
    ("two_riwayat", "mutual attack: grounded suspends (tawaqquf); two preferred extensions", 2, [(0, 1), (1, 0)]),
    ("reinstatement", "naqḍ (1) against a qiyās (2) is itself defeated by (0)", 3, [(0, 1), (1, 2)]),
    ("self_attack", "a self-defeating argument", 1, [(0, 0)]),
    ("odd_cycle", "three-cycle", 3, [(0, 1), (1, 2), (2, 0)]),
    ("chain4", "alternating chain", 4, [(0, 1), (1, 2), (2, 3)]),
    ("defended_by_two", "attacker defeated twice", 4, [(1, 0), (2, 1), (3, 1)]),
]


def grounded(n: int, attacks: list[tuple[int, int]]) -> list[int]:
    """Least fixpoint of F, by iteration from ∅."""
    attackers = {a: {b for b, x in attacks if x == a} for a in range(n)}
    s: frozenset[int] = frozenset()
    while True:
        nxt = frozenset(a for a in range(n) if all(attackers[b] & s for b in attackers[a]))
        if nxt == s:
            return sorted(s)
        s = nxt


def vectors() -> list[dict]:
    rng = random.Random(1421)
    named = [{"id": i, "note": note, "n": n, "attacks": [list(e) for e in att]} for i, note, n, att in NAMED]
    rand = [
        {"id": f"random_{k:02d}", "note": "seeded random", "n": n,
         "attacks": sorted([a, b] for a in range(n) for b in range(n) if rng.random() < 0.25)}
        for k, n in enumerate(rng.randint(1, 7) for _ in range(40))
    ]
    return [{**v, "grounded": grounded(v["n"], [tuple(e) for e in v["attacks"]])} for v in named + rand]


def stress_afs(seed: int, count: int, n_max: int, num: int, den: int):
    """The generated AFs: n = 1 + r mod n_max, then each ordered pair (a, b) attacks iff r mod den < num,
    r the high 31 bits of the next LCG state."""
    x = seed

    def draw() -> int:
        nonlocal x
        x = (LCG_A * x + LCG_C) % MOD64
        return x >> 33

    for _ in range(count):
        n = 1 + draw() % n_max
        yield n, [(a, b) for a in range(n) for b in range(n) if draw() % den < num]


def stress_digest(spec: dict) -> dict:
    """Fingerprint (polynomial hash mod 2^61-1 of each grounded set's bitmask + 1), the count of non-empty
    grounded sets, and the total number of grounded members."""
    h = nonempty = members = 0
    for n, att in stress_afs(**spec):
        g = grounded(n, att)
        h = (h * 1000003 + sum(1 << a for a in g) + 1) % P61
        nonempty += bool(g)
        members += len(g)
    return {"fingerprint": h, "nonempty": nonempty, "members": members}


def stress_lean(spec: dict, d: dict) -> str:
    return f"""-- GENERATED by formal/fixtures/gen_grounded.py from grounded-stress-v1.json. Do not edit.
-- M5 differential exit: {spec["count"]} AFs regenerated from a seeded MMIX LCG; the executable grounded
-- extension must reproduce the digest the Python reference and the Haskell oracle compute.
import Usul.Grounded

namespace UsulTest.GroundedStress

def lcg (x : Nat) : Nat := ({LCG_A} * x + {LCG_C}) % {MOD64}

/-- `count` AFs as (n, attacks), drawn exactly as `gen_grounded.stress_afs`. -/
def afs (seed count nMax num den : Nat) : List (Nat × List (Nat × Nat)) :=
  ((List.range count).foldl (fun (x, acc) _ =>
    let x := lcg x
    let n := 1 + (x / 2 ^ 33) % nMax
    let (x, att) := (List.range (n * n)).foldl (fun (x, att) k =>
      let x := lcg x
      (x, if (x / 2 ^ 33) % den < num then att ++ [(k / n, k % n)] else att)) (x, [])
    (x, acc ++ [(n, att)])) (seed, [])).2

def mask (g : List Nat) : Nat := g.foldl (fun m a => m + 2 ^ a) 0

def digest (vs : List (Nat × List (Nat × Nat))) : Nat × Nat × Nat :=
  vs.foldl (fun (h, ne, mem) (n, att) =>
    let g := Usul.Grounded.grounded n att
    ((h * 1000003 + mask g + 1) % {P61}, ne + (if g.isEmpty then 0 else 1), mem + g.length)) (0, 0, 0)

#guard digest (afs {spec["seed"]} {spec["count"]} {spec["n_max"]} {spec["num"]} {spec["den"]}) ==
  ({d["fingerprint"]}, {d["nonempty"]}, {d["members"]})

end UsulTest.GroundedStress
"""


def lean(vs: list[dict]) -> str:
    rows = ",\n".join(
        f'  ("{v["id"]}", {v["n"]}, {[tuple(e) for e in v["attacks"]]!s}, {v["grounded"]})'.replace("'", "")
        for v in vs
    )
    return (
        "-- GENERATED by formal/fixtures/gen_grounded.py from grounded-v1.json. Do not edit.\n"
        "import Usul.Grounded\n\nnamespace UsulTest\n\n"
        "def groundedVectors : List (String × Nat × List (Nat × Nat) × List Nat) := [\n"
        f"{rows}\n]\n\n"
        "#guard groundedVectors.all fun (_, n, att, g) => Usul.Grounded.grounded n att == g\n\n"
        "end UsulTest\n"
    )


def haskell(vs: list[dict], revision: str) -> str:
    st = json.loads(STRESS_OUT.read_text())
    g, d = st["generator"], st["digest"]
    stress = (f'(({g["seed"]}, {g["count"]}, {g["n_max"]}, {g["num"]}, {g["den"]}), '
              f'({d["fingerprint"]}, {d["nonempty"]}, {d["members"]}))')
    rows = "\n  , ".join(
        f'("{v["id"]}", {v["n"]}, {[tuple(e) for e in v["attacks"]]!s}, {v["grounded"]})' for v in vs
    )
    return (
        "-- GENERATED from larsbx/usul-al-fiqh-deontic-circuits formal/fixtures/grounded-v1.json\n"
        f"-- at revision {revision}. Do not edit; regenerate with gen_grounded.py --haskell.\n"
        "module Usul.GroundedVectors (groundedVectors, groundedStress) where\n\n"
        "groundedVectors :: [(String, Int, [(Int, Int)], [Int])]\n"
        f"groundedVectors =\n  [ {rows}\n  ]\n\n"
        "-- | M5 differential exit: (seed, count, nMax, num, den) of the seeded MMIX LCG and the digest\n"
        "-- (fingerprint, non-empty, members) of the grounded extensions, from grounded-stress-v1.json.\n"
        "groundedStress :: ((Integer, Int, Int, Integer, Integer), (Integer, Int, Int))\n"
        f"groundedStress = {stress}\n"
    )


def main(argv: list[str]) -> int:
    vs = vectors()
    if "--haskell" in argv:
        out = Path(argv[argv.index("--haskell") + 1])
        rev = argv[argv.index("--revision") + 1] if "--revision" in argv else "working-tree"
        out.write_text(haskell(json.loads(JSON_OUT.read_text())["vectors"], rev))
        return 0
    JSON_OUT.write_text(json.dumps({"contract": "usul.grounded-extension", "version": 1, "vectors": vs},
                                   ensure_ascii=False, indent=1) + "\n")
    LEAN_OUT.parent.mkdir(parents=True, exist_ok=True)
    LEAN_OUT.write_text(lean(vs))
    d = stress_digest(STRESS)
    STRESS_OUT.write_text(json.dumps({"contract": "usul.grounded-extension", "version": 1,
                                      "generator": {"kind": "mmix-lcg", "a": LCG_A, "c": LCG_C, "modulus": MOD64,
                                                    "output": "state >> 33", **STRESS},
                                      "digest": {"hash": "h' = (h * 1000003 + mask + 1) mod (2^61 - 1)", **d}},
                                     indent=1) + "\n")
    STRESS_LEAN.write_text(stress_lean(STRESS, d))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
