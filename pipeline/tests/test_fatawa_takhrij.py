import json
from pathlib import Path

import jsonschema

from usul_corpus import fatawa_takhrij, takhrij

ROOT = Path(__file__).parents[2]
ANSWERS = {"islamqa.4652": {"title": "الوديعة إذا هلكت", "question": None, "summary": None,
                            "answer": "الوديعة أمانة عند المودَع، فإذا هلكت بغير تعد ولا تفريط فلا ضمان عليه ."}}


def case(**kw):
    c = {"far": "islamqa.4652.f001", "encoder": "trust_loss", "class": "derivable",
         "facts": {"hand": "trustee", "transgressed": False, "negligent": False}, "expected": False,
         "quote": "فإذا هلكت بغير تعد ولا تفريط فلا ضمان عليه", "note": "Depositee, no transgression or negligence: not liable."}
    return c | kw


def test_a_well_formed_case_passes():
    assert fatawa_takhrij.check([case()], ANSWERS) == {}


def test_the_quote_must_be_verbatim_in_its_answer():
    errs = fatawa_takhrij.check([case(quote="فلا يضمن أبدا")], ANSWERS)
    assert errs == {"islamqa.4652.f001": ["quote not found in islamqa.4652"]}
    assert fatawa_takhrij.check([case(quote=None)], ANSWERS)["islamqa.4652.f001"] == ["quote missing"]


def test_the_case_must_point_at_a_known_answer_once():
    assert fatawa_takhrij.check([case(far="islamqa.1.f001")], ANSWERS)["islamqa.1.f001"] == ["unknown answer islamqa.1"]
    assert fatawa_takhrij.check([case(), case()], ANSWERS)["islamqa.4652.f001"] == ["duplicate case"]


def test_kernel_checks_are_takhrijs():
    errs = fatawa_takhrij.check([case(expected=True)], ANSWERS)["islamqa.4652.f001"]
    assert errs == ["class contradicts the kernel's output"]


def test_lean_header_names_its_source_and_existing_takhrij_output_is_unchanged():
    lean = fatawa_takhrij.lean_file([case()])
    assert "corpus/fatawa/takhrij" in lean and "#guard (Usul.Muamalat.lossLiable .trustee false false) == false" in lean
    assert takhrij.lean_file([]).startswith("-- GENERATED by `python -m usul_corpus takhrij` from corpus/takhrij/*.json.")


def test_committed_tranches_are_valid_and_generated():
    files = sorted(f for f in (ROOT / "corpus/fatawa/takhrij").glob("*.json") if f.name != "report.json")
    if not files:
        import pytest
        pytest.skip("no fatwa tranche yet")
    schema = json.loads((ROOT / "schemas/takhrij_cases.schema.json").read_text())
    for f in files:
        jsonschema.validate(json.loads(f.read_text()), schema)
    cases = fatawa_takhrij.load(ROOT / "corpus")
    assert cases and all(c["far"].startswith("islamqa.") for c in cases)
    assert (ROOT / "formal/lean/UsulTest/FatawaTakhrij.lean").read_text() == fatawa_takhrij.lean_file(cases)
    assert "import UsulTest.FatawaTakhrij" in (ROOT / "formal/lean/UsulTest.lean").read_text()


def test_without_the_answers_every_check_but_the_quote_s_still_runs():
    """Review (#100): an LFS pointer checkout skipped the duplicate, identity and kernel checks too."""
    assert fatawa_takhrij.check([case(quote="unrelated text")], None) == {}
    assert fatawa_takhrij.check([case(), case()], None)["islamqa.4652.f001"] == ["duplicate case"]
    assert fatawa_takhrij.check([case(quote=None)], None)["islamqa.4652.f001"] == ["quote missing"]
    assert fatawa_takhrij.check([case(far="islamqa.x")], None)["islamqa.x"][0] == "far is not islamqa.<answer>.fNNN"
    assert fatawa_takhrij.check([case(expected=True)], None) == fatawa_takhrij.check([case(expected=True)], ANSWERS)
