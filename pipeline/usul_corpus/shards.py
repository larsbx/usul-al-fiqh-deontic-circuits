"""Write isolation for parallel tranches (docs/architecture/derivation-method.md §5).

A shard of a parallel run writes only files it owns. Every shared registry is therefore a
committed base plus per-shard fragments, merged here with a hard error on a duplicate key:

* encoders: ``takhrij.CORE`` plus ``usul_corpus/encoders/<shard>.py`` (each exposes ``ENCODERS``);
* dossier entries: ``corpus/dossier/refinements.json`` plus ``corpus/dossier/entries/*.json``;
* reconciliation ledger: ``corpus/reconciliation/ledger.json`` plus ``corpus/reconciliation/entries/*.json``;
* Lean readings: ``formal/lean/Usul/Readings/<Shard>.lean``, imported by the generated ``Usul/Readings.lean``.

A shard declares the obligations it works on in ``corpus/worklists/claims/<shard>.json``. Claims name a
full base commit, only pending obligations, and no obligation another shard claims.
"""

from __future__ import annotations

import importlib
import json
import pkgutil
import re
from pathlib import Path

_SHA = re.compile(r"^[0-9a-f]{40}$")


def with_fragments(base: dict, fragments: Path, key: str) -> dict:
    """``base`` with the ``entries`` of every ``fragments/*.json`` appended, keys unique."""
    seen = {e[key]: "base" for e in base["entries"]}
    entries = list(base["entries"])
    for p in sorted(fragments.glob("*.json")) if fragments.is_dir() else ():
        for e in json.loads(p.read_text(encoding="utf-8"))["entries"]:
            if e[key] in seen:
                raise ValueError(f"{e[key]}: {seen[e[key]]} and {p.name}")
            seen[e[key]] = p.name
            entries.append(e)
    return {**base, "entries": entries}


def merge_encoders(core: dict[str, dict], shard_encoders: dict[str, dict[str, dict]]) -> dict[str, dict]:
    """The core encoders and every shard's, with no name defined twice."""
    owner = dict.fromkeys(core, "core")
    merged = dict(core)
    for shard, encoders in sorted(shard_encoders.items()):
        for name, enc in encoders.items():
            if name in owner:
                raise ValueError(f"{name}: {owner[name]} and {shard}")
            owner[name] = shard
            merged[name] = enc
    return merged


def encoder_shards() -> dict[str, dict[str, dict]]:
    """``ENCODERS`` of every module in the ``usul_corpus.encoders`` package, by module name."""
    from . import encoders
    return {m.name: importlib.import_module(f"{encoders.__name__}.{m.name}").ENCODERS
            for m in pkgutil.iter_modules(encoders.__path__)}


def readings_index(readings: Path) -> str:
    """The generated ``Usul/Readings.lean``: one import per shard reading module."""
    mods = sorted(p.stem for p in readings.glob("*.lean")) if readings.is_dir() else []
    return "\n".join(["-- GENERATED by `python -m usul_corpus signature` from formal/lean/Usul/Readings/*.lean. Do not edit.",
                      "-- Shard readings live one module per shard (docs/architecture/derivation-method.md §5).",
                      *(f"import Usul.Readings.{m}" for m in mods)]) + "\n"


def load_claims(corpus: Path) -> list[dict]:
    d = corpus / "worklists" / "claims"
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(d.glob("*.json"))] if d.is_dir() else []


def pending_obligations(corpus: Path) -> set[str]:
    """Unit ids still awaiting annotation, from every generated worklist inventory."""
    return {f for p in sorted((corpus / "worklists").glob("*_m8.json"))
            for q in json.loads(p.read_text(encoding="utf-8"))["qawaid"] for f in q["pending_furu"]}


def check_claims(claims: list[dict], pending: set[str]) -> list[str]:
    errors, owner = [], {}
    for c in claims:
        errors += [f"{c['shard']}: base_commit is not a full commit sha"] * (not _SHA.match(c.get("base_commit", "")))
        errors += [f"{c['shard']}: {o} is not a pending obligation" for o in c["obligations"] if o not in pending]
    for c in claims:
        for o in c["obligations"]:
            if o in owner:
                errors.append(f"{o}: claimed by {owner[o]} and {c['shard']}")
            owner.setdefault(o, c["shard"])
    return errors
