"""The bank applied to its own contradictions: truth tables → Lean guards (`Usul.Tanaqud`).

Each pair in `corpus/tanaqud/*.json` (sadi.json, then the others) carries a table: for every
case, the first and second qāʿida read without their qayd, and the jamʿ. Lean checks every row (`UsulTest/TanaqudTable.lean`,
generated); the Prolog oracle (`formal/oracle/tanaqud_oracle.pl`) checks the same rows against its
own model of the pairs.
"""

from __future__ import annotations

import json


def _value(v) -> str:
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, str):
        return f".{v}"
    return str(v)


def _case(c: list) -> str:
    return _value(c[0]) if len(c) == 1 else f"({', '.join(map(_value, c))})"


def _rule(r) -> str:
    return f"Q{r}" if isinstance(r, int) else r


def registers(corpus) -> list[dict]:
    """sadi.json first, then the other registers by name: the pair ids run on across them."""
    paths = sorted((corpus / "tanaqud").glob("*.json"), key=lambda p: (p.stem != "sadi", p.stem))
    return [json.loads(p.read_text(encoding="utf-8")) for p in paths]


def table_lean(regs: list[dict]) -> str:
    body = []
    for p in (p for reg in regs for p in reg["pairs"]):
        t = f"Usul.Tanaqud.t{int(p['id'][2:])}"
        body.append(f"-- {p['id']}: {_rule(p['rules'][0])} ⟂ {_rule(p['rules'][1])}")
        body += [f"#guard {t}.{side} {_case(r['case'])} == {_value(r[side])}"
                 for r in p["table"] for side in ("first", "second", "jam")]
    return ("-- GENERATED by `python -m usul_corpus signature` from corpus/tanaqud/*.json. Do not edit.\n"
            "import Usul\n\n" + "\n".join(body) + "\n")
