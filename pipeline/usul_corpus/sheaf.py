"""M10: every genuine ikhtilāf as a sheaf obstruction (`Usul.Cat.Sheaf`).

A takhrīj case's positions all speak to one situation, the farʿ. Read as patches of a cover of
that point (`Sheaf.positions`), they glue iff they agree (`positions_glue_iff`); a disagreement is
an obstruction record. This module emits one record per unordered pair of positions with
different rulings, and a Lean guard per case pinning the kernel's count of ordered obstruction
pairs (`Sheaf.obstructions`) to twice the records. The kernel is the authority over this mirror.

Not every position is a view the reading can express: its ruling may lie outside the encoder's
range (`out`), as with murāḍāt, muhāyaʾa or the heirs' oaths against a `lots` reading. Such a
position can never equal the case's expected ruling. Its obstructions are a range gap, not an
ikhtilāf the reading could adjudicate, so `outside` lists those positions and the summary
separates the records whose two positions are both within the reading.

The records are typed by the types layer (`corpus/types/encoders.json`, `Usul.Judgement`). Each
carries its encoder's sort and question. Two answers conflict only when they answer the same
question (`Judgement.Conflicts`), and only a `judgement`-sort encoder answers a khiṭāb. So a record
within the reading counts as a conflict of khiṭāb exactly when its sort is `judgement`. On an
effect, dalāla, takyīf, epistemic or procedure encoder it is a disagreement of another kind.
"""

from __future__ import annotations

import json
from itertools import combinations
from pathlib import Path

from collections import Counter

from . import judgement
from .takhrij import ENCODERS

OUTPUT = Path("sheaf") / "obstructions.json"
LEAN = "Obstructions.lean"


def _key(r: object) -> str:
    return json.dumps(r, ensure_ascii=False, sort_keys=True)


def rulings(case: dict) -> list[int]:
    """Each position's ruling as the index of its first occurrence: equal rulings, equal codes."""
    keys = [_key(p["ruling"]) for p in case["positions"]]
    return [keys.index(k) for k in keys]


def obstructions(case: dict) -> list[list[int]]:
    rs = rulings(case)
    return [[i, j] for i, j in combinations(range(len(rs)), 2) if rs[i] != rs[j]]


def outside(case: dict) -> list[int]:
    """Positions whose ruling the case's encoder cannot output."""
    out = ENCODERS[case["encoder"]]["out"]
    return [k for k, p in enumerate(case["positions"]) if p["ruling"] not in out]


def ikhtilaf(cases: list[dict]) -> list[dict]:
    return sorted((c for c in cases if c["class"] == "genuine_ikhtilaf"), key=lambda c: c["far"])


def within(row: dict) -> list[list[int]]:
    """The records whose two positions the reading can both express."""
    return [[i, j] for i, j in row["obstructions"] if i not in row["outside"] and j not in row["outside"]]


def render(cases: list[dict], types: dict[str, dict]) -> dict:
    rows = [{"far": c["far"], "encoder": c["encoder"], "sort": types[c["encoder"]]["sort"],
             "question": types[c["encoder"]].get("question"), "positions": len(c["positions"]),
             "outside": outside(c), "obstructions": obstructions(c)} for c in ikhtilaf(cases)]
    by_sort = Counter()
    for r in rows:
        by_sort[r["sort"]] += len(within(r))
    summary = {"cases": len(rows), "obstructed": sum(bool(r["obstructions"]) for r in rows),
               "records": sum(len(r["obstructions"]) for r in rows),
               "records_within_reading": sum(by_sort.values()),
               "conflicts_of_khitab": by_sort["judgement"],
               "records_within_reading_by_sort": dict(sorted(by_sort.items())),
               "positions_outside_reading": sum(len(r["outside"]) for r in rows)}
    return {"summary": summary, "cases": rows}


def lean_file(cases: list[dict]) -> str:
    lines = ["-- GENERATED by `python -m usul_corpus sheaf` from the takhrīj corpus. Do not edit.",
             "-- One guard per genuine_ikhtilāf case: its positions, as patches over the farʿ, emit",
             f"-- twice as many ordered obstruction pairs as `corpus/{OUTPUT.as_posix()}` records.",
             "import Usul", "", "open Usul.Cat.Sheaf", ""]
    for c in ikhtilaf(cases):
        rs = ", ".join(map(str, rulings(c)))
        lines += [f"-- {c['far']}", f"#guard (obstructions [()] (positions [{rs}])).length == {2 * len(obstructions(c))}"]
    return "\n".join(lines) + "\n"
