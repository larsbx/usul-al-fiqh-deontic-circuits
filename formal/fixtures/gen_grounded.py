"""Canonical grounded-extension vectors (single source of truth) and their
Lean / Haskell renderings. Python is the reference; Lean and Haskell each
recompute and must agree.

    python3 formal/fixtures/gen_grounded.py            # write JSON + Lean
    python3 formal/fixtures/gen_grounded.py --haskell PATH
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
JSON_OUT = HERE / "grounded-v1.json"
LEAN_OUT = HERE.parent / "lean" / "UsulTest" / "GroundedVectors.lean"

NAMED = [
    ("unattacked", "an uncontested naṣṣ", 1, []),
    ("two_riwayat", "mutual attack: grounded suspends (tawaqquf); two preferred extensions", 2, [(0, 1), (1, 0)]),
    ("reinstatement", "naqḍ (1) against a qiyās (2) is itself defeated by (0)", 3, [(0, 1), (1, 2)]),
    ("self_attack", "a self-defeating argument", 1, [(0, 0)]),
    ("odd_cycle", "three-cycle", 3, [(0, 1), (1, 2), (2, 0)]),
    ("chain4", "alternating chain", 4, [(0, 1), (1, 2), (2, 3)]),
    ("defended_by_two", "attacker defeated twice", 4, [(1, 0), (2, 1), (3, 1)]),
]


def grounded(n: int, attacks: list[tuple[int, int]]) -> list[int]:
    """Least fixpoint of F, by iteration from ∅."""
    attackers = {a: {b for b, x in attacks if x == a} for a in range(n)}
    s: frozenset[int] = frozenset()
    while True:
        nxt = frozenset(a for a in range(n) if all(attackers[b] & s for b in attackers[a]))
        if nxt == s:
            return sorted(s)
        s = nxt


def vectors() -> list[dict]:
    rng = random.Random(1421)
    named = [{"id": i, "note": note, "n": n, "attacks": [list(e) for e in att]} for i, note, n, att in NAMED]
    rand = [
        {"id": f"random_{k:02d}", "note": "seeded random", "n": n,
         "attacks": sorted([a, b] for a in range(n) for b in range(n) if rng.random() < 0.25)}
        for k, n in enumerate(rng.randint(1, 7) for _ in range(40))
    ]
    return [{**v, "grounded": grounded(v["n"], [tuple(e) for e in v["attacks"]])} for v in named + rand]


def lean(vs: list[dict]) -> str:
    rows = ",\n".join(
        f'  ("{v["id"]}", {v["n"]}, {[tuple(e) for e in v["attacks"]]!s}, {v["grounded"]})'.replace("'", "")
        for v in vs
    )
    return (
        "-- GENERATED by formal/fixtures/gen_grounded.py from grounded-v1.json. Do not edit.\n"
        "import Usul.Grounded\n\nnamespace UsulTest\n\n"
        "def groundedVectors : List (String × Nat × List (Nat × Nat) × List Nat) := [\n"
        f"{rows}\n]\n\n"
        "#guard groundedVectors.all fun (_, n, att, g) => Usul.Grounded.grounded n att == g\n\n"
        "end UsulTest\n"
    )


def haskell(vs: list[dict], revision: str) -> str:
    rows = "\n  , ".join(
        f'("{v["id"]}", {v["n"]}, {[tuple(e) for e in v["attacks"]]!s}, {v["grounded"]})' for v in vs
    )
    return (
        "-- GENERATED from larsbx/usul-al-fiqh-deontic-circuits formal/fixtures/grounded-v1.json\n"
        f"-- at revision {revision}. Do not edit; regenerate with gen_grounded.py --haskell.\n"
        "module Usul.GroundedVectors (groundedVectors) where\n\n"
        "groundedVectors :: [(String, Int, [(Int, Int)], [Int])]\n"
        f"groundedVectors =\n  [ {rows}\n  ]\n"
    )


def main(argv: list[str]) -> int:
    vs = vectors()
    if "--haskell" in argv:
        out = Path(argv[argv.index("--haskell") + 1])
        rev = argv[argv.index("--revision") + 1] if "--revision" in argv else "working-tree"
        out.write_text(haskell(json.loads(JSON_OUT.read_text())["vectors"], rev))
        return 0
    JSON_OUT.write_text(json.dumps({"contract": "usul.grounded-extension", "version": 1, "vectors": vs},
                                   ensure_ascii=False, indent=1) + "\n")
    LEAN_OUT.parent.mkdir(parents=True, exist_ok=True)
    LEAN_OUT.write_text(lean(vs))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
