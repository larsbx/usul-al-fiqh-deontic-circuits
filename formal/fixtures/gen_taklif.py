"""A behaviour of `formal/tla/Taklif.tla` (single source of truth) and its two renderings.

* TLA+: `formal/tla/TaklifTrace.tla` replays the behaviour through Taklif's own named actions. TLC
  deadlocks on any step the action does not produce, and checks that the first state is `Init`
  and that the spec's invariants and `BulughIrreversible` hold along it.
* Lean: `UsulTest/TaklifBehaviour.lean` gives the same behaviour in the Boolean-state fragment of
  `Usul.Cat.Carriers` (`traceI`). A state is abstracted by reading `bound` as `bound ≠ {}` and
  dropping `capable`; this abstraction is the model map from the TLA+ state space to the fragment.

    python3 formal/fixtures/gen_taklif.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
JSON_OUT = HERE / "taklif-behaviour-v1.json"
TLA_OUT = HERE.parent / "tla" / "TaklifTrace.tla"
CFG_OUT = HERE.parent / "tla" / "TaklifTrace.cfg"
LEAN_OUT = HERE.parent / "lean" / "UsulTest" / "TaklifBehaviour.lean"

DUTIES = ("salat", "sawm")
FLAGS = ("baligh", "aqil", "travelling", "rukhsa")

INIT = {"baligh": False, "aqil": True, "travelling": False, "rukhsa": False,
        "capable": list(DUTIES), "bound": []}
# (action, changes). Each state is the previous one with the changes applied.
STEPS = [
    ("Bulugh", {"baligh": True, "bound": ["salat", "sawm"]}),
    ("Incapacity(sawm)", {"capable": ["salat"], "bound": ["salat"]}),
    ("Depart", {"travelling": True}),
    ("TakeRukhsa", {"rukhsa": True}),
    ("Arrive", {"travelling": False, "rukhsa": False}),
    ("Recover(sawm)", {"capable": ["salat", "sawm"], "bound": ["salat", "sawm"]}),
    ("LoseAql", {"aqil": False, "bound": []}),
]


def states() -> list[dict]:
    out = [INIT]
    for _, changes in STEPS:
        out.append({**out[-1], **changes})
    return out


def _tla_bool(b: bool) -> str:
    return "TRUE" if b else "FALSE"


def _tla_set(xs: list[str]) -> str:
    return "{" + ", ".join(xs) + "}"


def _tla_state(s: dict) -> str:
    fields = [f"{k} |-> {_tla_bool(s[k])}" for k in FLAGS]
    fields += [f"capable |-> [d \\in Duties |-> d \\in {_tla_set(s['capable'])}]", f"bound |-> {_tla_set(s['bound'])}"]
    return "[" + ", ".join(fields) + "]"


def tla() -> str:
    ss = states()
    trace = ",\n       ".join(_tla_state(s) for s in ss)
    cases = "\n    [] ".join(f"k = {k} -> {a}" for k, (a, _) in enumerate(STEPS, 1))
    return f"""---------------------------- MODULE TaklifTrace ----------------------------
(***************************************************************************)
(* GENERATED by formal/fixtures/gen_taklif.py from taklif-behaviour-v1.json. *)
(* Do not edit. Trace validation: TLC replays the fixture behaviour through *)
(* Taklif's own actions and deadlocks on any step they do not produce.      *)
(***************************************************************************)
EXTENDS Taklif, Sequences

CONSTANTS salat, sawm

VARIABLE i

T == <<{trace}>>

At(k) == /\\ baligh = T[k].baligh /\\ aqil = T[k].aqil /\\ travelling = T[k].travelling
         /\\ rukhsa = T[k].rukhsa /\\ capable = T[k].capable /\\ bound = T[k].bound

AtNext(k) == /\\ baligh' = T[k].baligh /\\ aqil' = T[k].aqil /\\ travelling' = T[k].travelling
             /\\ rukhsa' = T[k].rukhsa /\\ capable' = T[k].capable /\\ bound' = T[k].bound

Step(k) == CASE {cases}

TraceInit == i = 1 /\\ At(1)

TraceNext == \\/ /\\ i < Len(T) /\\ i' = i + 1 /\\ Step(i) /\\ AtNext(i + 1)
             \\/ /\\ i = Len(T) /\\ UNCHANGED <<vars, i>>

TraceSpec == TraceInit /\\ [][TraceNext]_<<vars, i>>

StartsInInit == i = 1 => Init
=============================================================================
"""


def cfg() -> str:
    return f"""\\* GENERATED by formal/fixtures/gen_taklif.py. Do not edit.
CONSTANTS Duties = {_tla_set(list(DUTIES))}
          {chr(10).join(f'          {d} = {d}' for d in DUTIES).lstrip()}
SPECIFICATION TraceSpec
INVARIANTS StartsInInit OnlyMukallafBound OughtImpliesCan RukhsaNeedsSabab
PROPERTIES BulughIrreversible
"""


def _lean_state(s: dict) -> str:
    flags = [s[k] for k in FLAGS] + [bool(s["bound"])]
    return "st " + " ".join("true" if b else "false" for b in flags)


def lean() -> str:
    ss = states()
    rest = ",\n   ".join(_lean_state(s) for s in ss[1:])
    path = " → ".join(["Init", *(a for a, _ in STEPS)])
    return f"""-- GENERATED by formal/fixtures/gen_taklif.py from formal/fixtures/taklif-behaviour-v1.json. Do not edit.
-- The behaviour TLC replays in formal/tla/TaklifTrace.tla, abstracted to the Boolean-state fragment.
import Usul

namespace UsulTest.TaklifBehaviour

open Usul.Cat.Carriers

/-- A state from its flags: baligh, aqil, travelling, rukhsa, `bound ≠ {{}}`. -/
def st (b a t r d : Bool) : Fin 5 → Bool := fun i => match i.val with
  | 0 => b | 1 => a | 2 => t | 3 => r | _ => d

/-- {path}. -/
def behaviour : Trace 5 :=
  ⟨{_lean_state(ss[0])},
   [{rest}]⟩

end UsulTest.TaklifBehaviour
"""


def main() -> None:
    doc = {"contract": "taklif.behaviour", "version": 1, "spec": "formal/tla/Taklif.tla",
           "duties": list(DUTIES), "actions": [a for a, _ in STEPS], "states": states()}
    JSON_OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    TLA_OUT.write_text(tla(), encoding="utf-8")
    CFG_OUT.write_text(cfg(), encoding="utf-8")
    LEAN_OUT.write_text(lean(), encoding="utf-8")


if __name__ == "__main__":
    main()
