"""The bank applied to its own contradictions: truth tables → Lean guards (`Usul.Tanaqud`).

Each pair in `corpus/tanaqud/*.json` carries a table: for every case, the first and second
qāʿida read without their qayd, and the jamʿ. Lean checks every row (`UsulTest/TanaqudTable.lean`,
generated); the Prolog oracle (`formal/oracle/tanaqud_oracle.pl`) checks the same rows against its
own model of the pairs.
"""

from __future__ import annotations


def _value(v) -> str:
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, str):
        return f".{v}"
    return str(v)


def _case(c: list) -> str:
    return _value(c[0]) if len(c) == 1 else f"({', '.join(map(_value, c))})"


def table_lean(reg: dict) -> str:
    body = []
    for p in reg["pairs"]:
        t = f"Usul.Tanaqud.t{int(p['id'][2:])}"
        body.append(f"-- {p['id']}: Q{p['rules'][0]} ⟂ Q{p['rules'][1]}")
        body += [f"#guard {t}.{side} {_case(r['case'])} == {_value(r[side])}"
                 for r in p["table"] for side in ("first", "second", "jam")]
    return ("-- GENERATED by `python -m usul_corpus signature` from corpus/tanaqud/*.json. Do not edit.\n"
            "import Usul\n\n" + "\n".join(body) + "\n")
