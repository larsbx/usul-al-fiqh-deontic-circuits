"""al-Saʿdī's furūq: each item's grade → Lean guards (`Usul.Furuq`).

Every item records the madhhab's ruling, his grade and his own ruling; an item whose grade
overturns an earlier bare report names it (`overturns`), and Lean checks the pair is
`reported` → `daif` (`Usul.Furuq.overturn_iff_daif`). Lean checks the two rulings
against `Grade.madhhab` / `Grade.apart` (`UsulTest/FuruqTable.lean`, generated); the Prolog oracle
(`formal/oracle/furuq_oracle.pl`) checks them against its own model of the grades.
"""

from __future__ import annotations

from pathlib import Path
import json


def tranches(corpus: Path) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((corpus / "furuq").glob("sadi_tranche*.json"))]


def table_lean(corpus: Path) -> str:
    items = [i for t in tranches(corpus) for i in t["items"]]
    grade = {i["id"]: i["grade"] for i in items}
    body = [line for i in items for line in (
        f"-- {i['id']}: {i['grade']}",
        f"#guard Usul.Furuq.Grade.apart .{i['grade']} == {str(i['ruling'] == 'apart').lower()}",
        f"#guard Usul.Furuq.Grade.madhhab .{i['grade']} == {str(i['madhhab'] == 'apart').lower()}",
        *([f"-- {i['id']} overturns {i['overturns']} (Usul.Furuq.overturn_iff_daif)",
           f"#guard !Usul.Furuq.Grade.his .{grade[i['overturns']]} && Usul.Furuq.Grade.his .{i['grade']}"
           f" && Usul.Furuq.Grade.apart .{grade[i['overturns']]} != Usul.Furuq.Grade.apart .{i['grade']}"]
          if "overturns" in i else []))]
    return ("-- GENERATED by `python -m usul_corpus signature` from corpus/furuq/*.json. Do not edit.\n"
            "import Usul\n\n" + "\n".join(body) + "\n")
